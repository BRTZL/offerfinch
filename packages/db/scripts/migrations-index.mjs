// Writes src/migrations/index.ts: every migration's SQL as a string, so bundled apps carry
// them without reading a folder at run time. Run after `drizzle-kit generate`.
import fs from "node:fs";
import path from "node:path";

const dir = new URL("../src/migrations/", import.meta.url).pathname;
const names = fs
	.readdirSync(dir)
	.filter((name) => fs.existsSync(path.join(dir, name, "migration.sql")))
	.sort();
const body = names
	.map((name) => {
		const sql = fs.readFileSync(path.join(dir, name, "migration.sql"), "utf8");
		return `\t{ name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`;
	})
	.join("\n");
fs.writeFileSync(
	path.join(dir, "index.ts"),
	`// Generated by scripts/migrations-index.mjs. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`,
);
console.log(`${names.length} migrations indexed`);
